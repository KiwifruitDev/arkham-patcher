// Copies the patcher's source and the ps3xport WebAssembly files into the
// static site. The site repository only receives build artifacts; the source
// of truth lives here.

import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(here, '..');
const siteRoot = resolve(projectRoot, 'kiwifruitdev.com', 'public', 'arkhamrevived', 'ps3-tutorial');
const appDir = join(siteRoot, 'app');

const sourceFiles = [
  'app.js',
  'ui.js',
  'ui.css',
  'config.js',
  'pkg.js',
  'coalesced.js',
  'archive-patch.js',
];

const wasmFiles = [
  'engine.js',
  'pxfs.js',
  'host-directory.js',
  'host-remote.js',
  'sync-bridge.js',
  'layout.js',
  'writer.js',
  'zip.js',
  'ps3xport.wasm',
];

for (const name of wasmFiles) {
  const file = join(projectRoot, 'web', name);
  if (!existsSync(file)) {
    console.error(`Missing ${file}. Run "npm run build" in the ps3xport-wasm root first.`);
    process.exit(1);
  }
}

mkdirSync(appDir, { recursive: true });
rmSync(appDir, { recursive: true, force: true });
mkdirSync(appDir, { recursive: true });

for (const name of sourceFiles) cpSync(join(here, 'src', name), join(appDir, name));
for (const name of wasmFiles) cpSync(join(projectRoot, 'web', name), join(appDir, name));

// GitHub Pages serves .mjs correctly today, but .js is the safer bet for
// static hosts. Keep the Emscripten loader next to the worker as ps3xport.js.
cpSync(join(projectRoot, 'web', 'ps3xport.mjs'), join(appDir, 'ps3xport.js'));
const worker = readFileSync(join(projectRoot, 'web', 'worker.js'), 'utf8');
if (!worker.includes('./ps3xport.mjs')) {
  console.error('web/worker.js no longer imports ./ps3xport.mjs; update the build script.');
  process.exit(1);
}
writeFileSync(join(appDir, 'worker.js'), worker.replace('./ps3xport.mjs', './ps3xport.js'));

cpSync(join(here, 'src', 'coi-sw.js'), join(siteRoot, 'coi-sw.js'));
cpSync(join(here, 'LICENSE'), join(appDir, 'LICENSE'));
cpSync(join(projectRoot, 'COPYING'), join(appDir, 'COPYING'));

const publicRoot = join(projectRoot, 'kiwifruitdev.com', 'public');
writeFileSync(join(publicRoot, '_headers'), [
  '# Applied by hosts that support custom headers (Cloudflare Pages, Netlify).',
  '# GitHub Pages ignores this file; coi-sw.js adds the same headers at runtime.',
  '/arkhamrevived/ps3-tutorial/*',
  '  Cross-Origin-Opener-Policy: same-origin',
  '  Cross-Origin-Embedder-Policy: require-corp',
  '',
].join('\n'));

const notice = `Arkham: Revived - PlayStation 3 patcher

This folder is generated by arkham-patcher/build.mjs. Do not edit it by hand.

Components:
- ps3xport WebAssembly core (ps3xport by kakaroto, GPL-3.0-or-later), built from
  the ps3xport-wasm project: https://github.com/KiwifruitDev/ps3xport-wasm
- Web panel drivers from the same project (MIT, see the project's web/LICENSE).
- PKG reader ported from PyKG (MIT): https://github.com/AphelionWasTaken/PyKG
- Coalesced reader/writer ported from coalesced-inifier (GPL-3.0):
  https://github.com/ripdajacker/coalesced-inifier
- The combined build is GPL-3.0-or-later.
`;
writeFileSync(join(appDir, 'NOTICE.txt'), notice);

const total = sourceFiles.length + wasmFiles.length + 4;
console.log(`Copied ${total} files to ${appDir}`);
console.log(`Wrote ${join(siteRoot, 'coi-sw.js')} and ${join(publicRoot, '_headers')}`);
